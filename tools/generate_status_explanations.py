#!/usr/bin/env python3
"""Generate the status-explanation table from doc/status-message-help-draft.md."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DRAFT = ROOT / "doc" / "status-message-help-draft.md"


def entries(text):
    parts = text.split("\n## ")[1:]
    found = []
    for part in parts:
        lines = part.strip().splitlines()
        title = lines[0].strip()
        body = " ".join(line.strip() for line in lines[1:] if line.strip())
        if not title or not body:
            raise SystemExit(f"empty status explanation for {title!r}")
        found.append((title, body))
    if len(found) < 2:
        raise SystemExit("status explanation draft has no entries")
    return found


def raw(text):
    if ")sep" in text:
        raise SystemExit("explanation contains the raw-string delimiter")
    return 'R"sep(' + text + ')sep"'


def pieces(title):
    return re.split(r"<[^>]+>", title)


def main():
    output = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "src/ui/status_explanation_data.inc"
    rows = entries(DRAFT.read_text(encoding="utf-8"))
    exact = []
    patterns = []
    for title, body in rows:
        if "<" in title:
            parts = pieces(title)
            if any(not part for part in (parts[0], parts[-1])):
                raise SystemExit(f"placeholder is not between fixed text: {title}")
            patterns.append((parts, body))
        else:
            exact.append((title, body))
    lines = [
        "// Generated by tools/generate_status_explanations.py from",
        "// doc/status-message-help-draft.md. Do not edit this file.",
        "struct ExactExplanation { const char* message; const char* explanation; };",
        "struct PatternExplanation { const char* prefix; const char* middle; const char* suffix; const char* explanation; };",
        "static constexpr ExactExplanation exactExplanations[] = {",
    ]
    for title, body in exact:
        lines.append(f"    {{{raw(title)}, {raw(body)}}},")
    lines.append("};")
    lines.append("static constexpr PatternExplanation patternExplanations[] = {")
    for parts, body in patterns:
        prefix, suffix = parts[0], parts[-1]
        middle = parts[1] if len(parts) > 2 else ""
        if len(parts) > 3:
            raise SystemExit(f"too many placeholders: {prefix}")
        lines.append(f"    {{{raw(prefix)}, {raw(middle)}, {raw(suffix)}, {raw(body)}}},")
    lines.append("};")
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(exact)} exact, {len(patterns)} patterns -> {output}")


if __name__ == "__main__":
    main()
