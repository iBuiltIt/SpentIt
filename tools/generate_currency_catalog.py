"""Generate/check code-scale facts from the pinned SIX List One snapshot (offline)."""
import argparse
import hashlib
import json
import re
from pathlib import Path
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parents[1]
source = root / 'third_party/iso4217/list-one.xml'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
xml = ET.parse(source).getroot()
entries = {}
for entry in xml.findall('.//CcyNtry'):
    code, scale = entry.findtext('Ccy'), entry.findtext('CcyMnrUnts')
    if not code or scale == 'N.A.':
        continue
    if not scale:
        raise ValueError('Missing minor-unit definition')
    if len(code) != 3 or not code.isascii() or not code.isalpha() or not code.isupper():
        raise ValueError('Invalid currency code in snapshot')
    if not scale.isascii() or not scale.isdigit() or not 0 <= int(scale) <= 9:
        raise ValueError('Unsupported scale in snapshot')
    if code in entries and entries[code] != int(scale):
        raise ValueError('Conflicting currency scales')
    entries[code] = int(scale)
if not entries:
    raise ValueError('Empty catalog')
output = '// Generated by tools/generate_currency_catalog.py; do not edit.\n'
output += '// SIX List One published ' + xml.attrib['Pblshd'] + '\n'
output += ''.join(f'    {{"{code}", {scale}}},\n' for code, scale in sorted(entries.items()))
# This retained registry is deliberately NOT derived from the current catalog.
# Removing a selection must never remove an amount definition.
reference = root / 'third_party/iso4217'
for name, digest in {
    'list-one-2026-09-17.xml': '33139b438657d1cee116ba737807ea71d19d6de4b90f799a09c56f0cc6a1b0ff',
    'amendment-174.pdf': 'bf19b1aa9908a1368fdef34151454ecfe664ce83b50a4c6e75bbdf8dd7f64e80',
    'amendment-180.pdf': '8b2a8a146b2dbaa4d95734b3615ef71db7c4642e75f13e38197101f082f5a8a3',
}.items():
    if hashlib.sha256((reference / name).read_bytes()).hexdigest() != digest:
        raise ValueError('Retained reference checksum mismatch')
archived = {e.findtext('Ccy'): int(e.findtext('CcyMnrUnts'))
            for e in ET.parse(reference / 'list-one-2026-09-17.xml').findall('.//CcyNtry')
            if e.findtext('Ccy') and (e.findtext('CcyMnrUnts') or '').isdigit()}
definitions = json.loads((reference / 'amount-definitions.json').read_text())
by_id = {}
for definition in definitions:
    identifier, code, scale = definition['id'], definition['code'], definition['scale']
    if not re.fullmatch(r'[A-Za-z0-9:-]+', identifier) or identifier in by_id:
        raise ValueError('Invalid or duplicate definition identity')
    if not re.fullmatch(r'[A-Z]{3}', code) or type(scale) is not int or not 0 <= scale <= 9:
        raise ValueError('Invalid retained currency definition')
    if definition['source'] not in ('list-one-2026-09-17.xml', 'amendment-174.pdf', 'amendment-180.pdf'):
        raise ValueError('Unreviewed reference source')
    if not (reference / definition['source']).is_file():
        raise ValueError('Missing reference source')
    facts = archived if definition['source'].endswith('.xml') else (
        {'HRK': 2} if definition['source'] == 'amendment-174.pdf' else {'BGN': 2})
    if facts.get(code) != scale:
        raise ValueError('Retained definition disagrees with reviewed source facts')
    by_id[identifier] = definition
selection = json.loads((reference / 'current-definitions.json').read_text())
if set(selection) != set(entries):
    raise ValueError('Selection and current catalog differ')
for code, identifier in selection.items():
    definition = by_id[identifier]
    if (definition['code'], definition['scale']) != (code, entries[code]):
        raise ValueError('Selection disagrees with retained definition')
outputs = {
    'currency_catalog.inc': output.split('\n', 1)[1],
    'amount_currency_definitions.inc': ''.join(
        f'    {{"{d["id"]}", "{d["code"]}", {d["scale"]}}},\n'
        for d in sorted(definitions, key=lambda d: d['id'])),
    'currency_selection.inc': ''.join(f'    {{"{c}", "{i}"}},\n' for c, i in sorted(selection.items())),
}
for name, contents in outputs.items():
    path = root / 'src/engine' / name
    contents = '// Generated by tools/generate_currency_catalog.py; do not edit.\n' + contents
    if args.check:
        if path.read_text() != contents:
            raise SystemExit(f'{name} differs from retained definitions')
    else:
        path.write_text(contents)

if args.check:
    print(f"Verified {len(entries)} current choices and {len(definitions)} retained definitions")
